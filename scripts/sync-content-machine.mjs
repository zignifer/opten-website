import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validateContentMachineSnapshot } from "./content-machine-contract.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceArg = readArg("--source");
if (!sourceArg) {
  throw new Error("Usage: npm run sync:content-machine -- --source <content-machine.json>");
}

const source = path.resolve(sourceArg);
const target = path.join(root, "api", "admin", "_contentMachineSnapshot.ts");
const encoded = await readFile(source, "utf8");
const snapshot = JSON.parse(encoded);
const { bytes } = validateContentMachineSnapshot(snapshot, encoded);
const normalized = JSON.stringify(snapshot, null, 2);
const moduleSource = [
  "// Generated by scripts/sync-content-machine.mjs. Do not edit by hand.",
  `export const CONTENT_MACHINE_SNAPSHOT = ${normalized} as const;`,
  "",
].join("\n");

await writeFile(target, moduleSource, "utf8");
console.log(`content-machine sync: ${snapshot.generatedAt} · ${bytes} bytes`);

function readArg(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : null;
}
